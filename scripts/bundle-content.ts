// Bundles data/guides/*.json and skills/*/SKILL.md into lib/generated/content.ts.
// Runs before build and tests (npm prebuild / pretest), so the deployed app never depends on
// reading files from disk at runtime (Vercel's file tracing can drop them).
import fs from "node:fs";
import path from "node:path";

const root = path.join(__dirname, "..");
const guidesDir = path.join(root, "data", "guides");
const skillsDir = path.join(root, "skills");

const guides = fs.readdirSync(guidesDir).filter((f) => f.endsWith(".json")).sort()
  .map((f) => JSON.parse(fs.readFileSync(path.join(guidesDir, f), "utf8")));

const skills = fs.readdirSync(skillsDir).sort()
  .filter((d) => fs.existsSync(path.join(skillsDir, d, "SKILL.md")))
  .map((d) => ({ dir: d, text: fs.readFileSync(path.join(skillsDir, d, "SKILL.md"), "utf8") }));

const out = `// Generated by scripts/bundle-content.ts. Do not edit; edit data/guides and skills instead.
/* eslint-disable */
export const GUIDES: unknown[] = ${JSON.stringify(guides)};
export const SKILL_FILES: { dir: string; text: string }[] = ${JSON.stringify(skills)};
`;
fs.mkdirSync(path.join(root, "lib", "generated"), { recursive: true });
fs.writeFileSync(path.join(root, "lib", "generated", "content.ts"), out);
console.log(`Bundled ${guides.length} guides and ${skills.length} skills.`);
