"use client";
import { Fragment, useState } from "react";
import { type Guide, type Note, type Status, HANDOFF_LEVELS, OWNER_LABEL, SECTION_TITLES, STATUS_LABEL } from "@/lib/schema";

/** Renders `code` spans inside plain text. */
export function Rich({ text }: { text?: string }) {
  if (!text) return null;
  const parts = text.split(/(`[^`]+`)/g);
  return <>{parts.map((p, i) => (p.startsWith("`") && p.endsWith("`") ? <code key={i}>{p.slice(1, -1)}</code> : <Fragment key={i}>{p}</Fragment>))}</>;
}

export function StatusBadge({ s }: { s?: Status }) {
  if (!s) return null;
  return <span className={`badge st-${s}`}>{STATUS_LABEL[s] ?? s}</span>;
}

export function Meter({ n, tone }: { n: number; tone: "g" | "a" | "r" }) {
  return (
    <span className={`meter m-${tone}`} aria-label={`${n} of 5`}>
      {[1, 2, 3, 4, 5].map((i) => <i key={i} className={i <= n ? "on" : ""} />)}
    </span>
  );
}
const toneFor = (n: number): "g" | "a" | "r" => (n <= 2 ? "g" : n === 3 ? "a" : "r");

function Head({ k, state }: { k: string; state?: string }) {
  const t = SECTION_TITLES[k];
  return (
    <div className="sh">
      <span className="num">{t.num}</span>
      <h2>{t.title}</h2>
      {state ? <span className={`state ${state.startsWith("Writing") ? "writing" : ""}`}>{state}</span> : <span className="q">{t.question}</span>}
    </div>
  );
}

function Callout({ n }: { n: Note }) {
  return (
    <div className={`callout tone-${n.tone ?? "info"}`}>
      <b className="t"><Rich text={n.title} /></b>
      <Rich text={n.text} /> <StatusBadge s={n.status} />
    </div>
  );
}

const Pending = ({ k, writing }: { k: string; writing?: boolean }) => (
  <section className="gs pending" id={`s-${k}`}><Head k={k} state={writing ? "Writing…" : "Waiting"} /><div className="skeleton" /></section>
);

