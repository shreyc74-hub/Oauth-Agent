// Provisioning: app name in, a sandbox account plus verified OAuth credentials out.
// One playbook shape for every provider. The engine runs any playbook step by step and persists
// the run after every step, so a run can pause for a person and resume on another server instance.

export type Mode = "human" | "auto";

/** How the OAuth app itself gets created. Browser automation is the fallback, not the strategy. */
export type Strategy = "api" | "browser" | "human" | "dcr";

/** Kinds of credential a vendor can offer. */
export type CredentialType = "oauth2" | "oauth1" | "client_credentials" | "api_key" | "jwt" | "service_account" | "basic" | "bearer";

/**
 * Everything the agent works out before anything is created or anyone is asked to choose a mode:
 * is a self-serve sandbox possible, which accounts are needed, which credentials the vendor offers,
 * which one to provision, how it gets created, and which mode the agent recommends.
 */
export interface Assessment {
  feasible: boolean;
  accounts: { relation: "same" | "separate" | "unknown"; sandbox: string; developer: string };
  credentials: { offered: { type: CredentialType; source: string; note?: string }[]; chosen: "oauth" | "api_key"; why: string };
  /** How the chosen credential gets created, best route first. `executable` = this agent can run it today. */
  route: { method: string; detail: string; executable: boolean; fallback?: string };
  modes: Record<Mode, { available: boolean; why: string }>;
  recommendedMode: Mode;
  recommendWhy: string;
  steps: { mode: Mode; count: number; human: string[] }[];
}

/**
 * One step. Steps are data, so a playbook can be written by hand (library apps) or generated by
 * the planner from a guide (any other app). Secrets are referred to by name and never inlined.
 */
/** Every step can be skipped when a shared credential already exists (e.g. Slack's config token). */
type Base = { id: string; title: string; skipIfVault?: string };

export type Step =
  /** Create the agent's own identity for this provider: an inbox and a generated password. */
  | (Base & { kind: "identity" })
  /** Natural-language browser action. `%name%` placeholders are filled from the vault and never sent to the model. */
  | (Base & { kind: "browser"; url?: string; instruction?: string; secrets?: string[]; write?: boolean })
  /** Read a value off the page deterministically (the model only finds the element) and put it straight in the vault. */
  | (Base & { kind: "capture"; find: string; reveal?: string; into: string; secret: boolean })
  /** Wait for an email to the agent inbox and pull a code or link out of it. */
  | (Base & { kind: "email"; from?: string; extract: "code" | "link"; then?: string })
  /** Turn on authenticator 2FA and keep the TOTP seed so the agent can make its own codes. */
  | (Base & { kind: "totp"; find: string; codeField: string })
  /** Provider API call done in code (e.g. Slack's apps.manifest.create). Named handler on the playbook. */
  | (Base & { kind: "api"; handler: string; write?: boolean })
  /** Something only a person can do (captcha, phone check, legal terms in some modes). */
  | (Base & { kind: "human"; reason: string; url?: string; noBrowser?: boolean })
  /** Run the OAuth flow against the sandbox, call an identity endpoint, test the refresh token. */
  | (Base & { kind: "verify" })
  /** Mark what production approval needs. Never automated. */
  | (Base & { kind: "golive" });

export interface OAuthSpec {
  authorizeUrl: string;
  tokenUrl: string;
  /** Endpoint that proves the token works. GraphQL bodies allowed. */
  whoami: { url: string; method?: "GET" | "POST"; body?: unknown; pick: string };
  scopes: string[];
  scopeSeparator?: string;
  /** How the client authenticates at the token endpoint. */
  clientAuth?: "body" | "basic";
  extraAuthorizeParams?: Record<string, string>;
  /** Phrase the agent uses to click the consent button. */
  consentInstruction: string;
  refresh: "yes" | "no" | "if-enabled";
}

export interface Playbook {
  slug: string;
  name: string;
  strategy: Strategy;
  /** Where the evidence for this playbook comes from. Generated playbooks start "unverified". */
  evidence: "tested" | "docs" | "unverified";
  sandbox: { kind: string; note: string; relation?: "same" | "separate" };
  /** What gets provisioned. Default "oauth". */
  credential?: "oauth" | "api_key";
  /** For credential "api_key": how the key is sent, and a read-only call that proves it works. */
  apiKey?: { header: string; prefix?: string; testUrl: string; pick?: string };
  oauth: OAuthSpec;
  /** Steps per mode. Modes share most steps; sign-up differs. */
  steps: Record<Mode, Step[]>;
  /** What going live needs, from the guide's approval section. */
  goLive: { needed: boolean; summary: string; humanWork: string[] };
  notes?: string[];
}

export type RunStatus =
  | "ready" //            researched; waiting for a person to choose the mode and start
  | "queued"
  | "running"
  | "waiting_human" //    a person must act in the live browser
  | "waiting_approval" // HITL: a write is about to happen
  | "verified" //         credentials proven against the sandbox
  | "needs_review" //     created but not verified
  | "failed"
  | "cancelled";

export interface RunEvent {
  at: string;
  step?: string;
  kind: "info" | "step" | "handoff" | "approval" | "secret" | "error" | "done" | "agent";
  text: string;
  shot?: string; // screenshot URL or data URI (never of a revealed secret)
}

/**
 * Can a stranger get a working test account without sales, a partner programme or an existing
 * subscription? Decided in code from quotes that were found on the cited pages and from a probe
 * of the sign-up page. Only "gated" (quoted evidence) stops a run.
 */
export type SandboxVerdict = "self_serve" | "likely_self_serve" | "gated" | "unknown";

/**
 * One piece of the setup, judged on its own evidence:
 *  developer_account  where the OAuth app is created and managed (api.slack.com, Zoho API Console)
 *  sandbox            the working environment the app is installed in and tested against
 *                     (a Slack workspace, a HubSpot test account, a Zoho Invoice organization)
 *  oauth_app          whether anyone can create an OAuth app at all, or only partners (or API keys only)
 */
export interface SetupPart {
  role: "developer_account" | "sandbox" | "oauth_app";
  name: string;
  url?: string;
  verdict: SandboxVerdict;
  reason: string;
  humanPath?: string;
  /** e.g. "14-day trial": the sandbox stops working after this. */
  expires?: string;
  quotes: { quote: string; url: string; says: "yes" | "no"; found: boolean }[];
  probe?: { url: string; finalUrl?: string; status?: number; signals: string[]; looks: "signup_form" | "sales_gate" | "unclear" | "unreachable" };
}

export interface SandboxCheck {
  /** One plain sentence for people: the answer before the evidence. */
  summary?: string;
  /** Is the sandbox the same account as the developer side (Linear, BambooHR) or a separate one (Slack, HubSpot, Zoho)? */
  relation?: "same" | "separate" | "unknown";
  parts?: SetupPart[];
  /** What credential a stranger can get: an OAuth app, only an API key, or OAuth for partners only. */
  credential?: { oauth: "self_serve" | "partner_only" | "none" | "unknown"; apiKey: boolean };
  /** Every credential type the vendor's pages say a stranger can create, with where. */
  offered?: { type: CredentialType; where?: string; selfServe: "yes" | "no" | "unclear"; quote?: { quote: string; url: string; found: boolean } }[];
  /** A way to create the OAuth app without the console, if the vendor documents one. */
  creation?: { kind: "management_api" | "cli" | "manifest"; detail: string; quote?: { quote: string; url: string; found: boolean } };
  verdict: SandboxVerdict;
  reason: string;
  /** What a person has to do when it is gated, e.g. "Apply to the partner programme". */
  humanPath?: string;
  signupUrl?: string;
  /** Quotes the research agent cited. `found` is set by code after fetching the page. */
  quotes: { quote: string; url: string; says: "yes" | "no"; found: boolean }[];
  probe?: { url: string; finalUrl?: string; status?: number; signals: string[]; looks: "signup_form" | "sales_gate" | "unclear" | "unreachable" };
  source: "playbook" | "research" | "run";
  checkedOn: string;
}

/** Use case -> scopes, and one read-only call from that use case that verification makes. */
export interface ScopePlan {
  useCase: string;
  scopes: string[];
  mapping: { need: string; scopes: string[]; why: string }[];
  testCall?: { method: "GET"; url: string; label: string };
  notes: string[];
}

/** Live progress while a run is being set up, streamed to the start page (like a network panel). */
export interface ProgressEvent { id: string; label: string; state: "start" | "done" | "fail" | "info"; detail?: string }
export type Progress = (e: ProgressEvent) => void;
export const noProgress: Progress = () => undefined;

/** A run as stored. Holds vault references, never secret values. */
export interface Run {
  id: string;
  app: string;
  slug: string;
  mode: Mode;
  status: RunStatus;
  strategy: Strategy;
  cursor: number; // index of the next step
  steps: { id: string; title: string; kind: Step["kind"]; state: "todo" | "doing" | "done" | "skipped" | "blocked"; recovered?: boolean }[];
  pending?: {
    kind: "human" | "approval";
    step: string;
    reason: string;
    /** When set, the person can type a value that goes straight into the vault (e.g. a secret the agent could not read). */
    field?: { into: string; secret: boolean; label: string };
    blocker?: string;
    /** Set when the recovery agent (not the playbook) wants to do this write. */
    recovery?: string;
  };
  /** Non-secret values the steps use: app name, workspace name, redirect URI, base URL. */
  vars: Record<string, string>;
  /** Snapshot of the plan, so a run keeps the same steps even if the playbook changes mid-run. */
  playbook: Playbook;
  /** Short lease so two browser tabs can't advance the same run at once. */
  lockUntil?: number;
  browser?: { sessionId: string; liveUrl?: string };
  identity?: { email?: string; inboxId?: string };
  vault: Record<string, string>; // label -> vault name, e.g. client_secret -> "linear/2026-11-14/client_secret"
  public: { clientId?: string; sandboxUrl?: string; appId?: string; authorizeUrl?: string };
  verify?: { state: string; verifier: string; code?: string; who?: string; refresh?: "ok" | "failed" | "not-offered"; at?: string; useCase?: string; useCaseOk?: boolean };
  sandbox?: SandboxCheck;
  assessment?: Assessment;
  /** What the run is waiting for while it waits (an email), so the page can say so instead of "Working". */
  waitingFor?: { what: string; since: number; until: number; hint?: string };
  scopePlan?: ScopePlan;
  /** Dynamic Client Registration probe: could the app be created with one API call? */
  dcr?: import("./dcr").DcrResult;
  goLive?: Playbook["goLive"];
  /** Where the recovery agent found a different route: suggested playbook changes for a person to review. */
  fixes?: { step: string; suggestion: string; at: string }[];
  sheetRow?: number;
  events: RunEvent[];
  createdAt: string;
  updatedAt: string;
}
